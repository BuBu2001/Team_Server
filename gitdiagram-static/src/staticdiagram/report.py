def _table(headers: list[str], rows: list[list[str]], numeric: Optional[set[int]] = None) -> str:
    numeric = numeric or set()
    out = ["<table><thead><tr>"]
    for index, header in enumerate(headers):
        out.append(f'<th class="num">{html.escape(header)}</th>' if index in numeric else f"<th>{html.escape(header)}</th>")
    out.append("</tr></thead><tbody>")
    for row in rows:
        out.append("<tr>")
        for index, cell in enumerate(row):
            klass = ' class="num"' if index in numeric else ""
            out.append(f"<td{klass}>{cell}</td>")
        out.append("</tr>")
    out.append("</tbody></table>")
    return "".join(out)


def _markdown_inline(text: str) -> str:
    escaped = html.escape(text)
    escaped = escaped.replace("`", "\x00")
    parts = escaped.split("\x00")
    rebuilt = parts[0]
    for index, part in enumerate(parts[1:]):
        rebuilt += f"<code>{part}</code>" if index % 2 == 0 else part
    return rebuilt


def write_html(
    analysis: Analysis,
    explanation: Explanation,
    mermaid: str,
    svg: str,
    destination: Path,
    issues: Optional[list] = None,
) -> Path:
    repo = analysis.repo
    meta = analysis.meta
    title = meta.name or repo.name
    graph = analysis.graph or DiagramGraph()

    component_rows = [
        [
            html.escape(component.label),
            _links(analysis, component.path),
            str(len(component.files)),
            f"{component.loc:,}",
            str(component.inbound),
            str(component.outbound),
            "".join(
                f'<span class="pill">{html.escape(signal)}</span>'
                for signal in sorted(component.signals)[:4]
            ),
        ]
        for component in analysis.selected()
    ]

    node_by_id = {node.id: node for node in graph.nodes}
    edge_rows = []
    for edge in graph.edges:
        source = node_by_id.get(edge.src)
        target = node_by_id.get(edge.dst)
        if not source or not target:
            continue
        evidence = (
            _links(analysis, edge.evidencePath)
            if edge.evidencePath
            else ("<em>external</em>" if not target.path else "\u2014")
        )
        edge_rows.append(
            [
                html.escape(source.label),
                html.escape(edge.label or "relates to"),
                html.escape(target.label)
                + (f" <span style='color:#94a3b8'>{html.escape(target.path or '')}</span>" if target.path else ""),
                evidence,
            ]
        )

    coverage = analysis.coverage
    coverage_items = [
        f"Repository files: <strong>{coverage.files_total}</strong>",
        f"Python modules parsed: <strong>{coverage.files_parsed}</strong>",
        f"Skipped (tests/examples/docs): <strong>{coverage.files_skipped_tests}</strong>",
        f"Skipped (vendored/oversized/sensitive): <strong>{coverage.files_skipped_other}</strong>",
        f"Internal imports resolved: <strong>{coverage.imports_resolved}</strong>",
        f"Imports to stdlib: <strong>{coverage.imports_stdlib}</strong>",
        f"Imports outside the repository: <strong>{coverage.imports_unresolved}</strong>",
        f"Components detected: <strong>{coverage.components_total}</strong> "
        f"(depth {coverage.depth}, {coverage.components_shown} on the diagram)",
        f"Unparsable files: <strong>{coverage.files_failed}</strong>",
    ]

    sections_html = []
    for heading, body in explanation.sections:
        if heading == "Overview":
            continue
        rendered = body
        if rendered.startswith("|"):
            continue  # tables are rendered natively below
        rendered_html = "\n".join(
            f"<li>{_markdown_inline(line.lstrip('- '))}</li>" if line.startswith("- ")
            else f"<p>{_markdown_inline(line)}</p>"
            for line in rendered.splitlines()
            if line.strip()
        )
        if "<li>" in rendered_html:
            rendered_html = f"<ul>{rendered_html.replace('</li><p>', '</li>').replace('<p>', '').replace('</p>', '')}</ul>" if rendered_html.count("<li>") > rendered_html.count("<p>") else rendered_html
        sections_html.append(f'<div class="card"><h2>{html.escape(heading)}</h2>{rendered_html}</div>')

    validation = ""
    if issues:
        rows = "".join(
            f"<li><code>{html.escape(issue.path)}</code> \u2014 {html.escape(issue.message)}</li>"
            for issue in issues
        )
        validation = f'<div class="card"><h2>Validation notes</h2><ul>{rows}</ul></div>'

    subtitle = " \u00b7 ".join(
        part
        for part in [
            f'<a href="https://github.com/{html.escape(repo.slug)}">{html.escape(repo.slug)}</a>'
            if repo.owner
            else html.escape(repo.origin),
            f"branch <code>{html.escape(repo.branch)}</code>",
            f"commit <code>{html.escape((repo.commit or 'unknown')[:10])}</code>" if repo.commit else "",
            f"{len(graph.nodes)} nodes \u00b7 {len(graph.edges)} edges",
        ]
        if part
    )

    document = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(title)} \u2014 architecture map</title>
<style>{HTML_STYLE}</style>
</head>
<body>
<main>
<header>
  <h1>{html.escape(title)}</h1>
  <div class="meta">{subtitle}</div>
  <div class="meta"><span class="badge">no AI</span> <span class="meta">static analysis of imports, entry points and infrastructure</span></div>
</header>

<div class="card">
  <h2>Overview</h2>
  <p>{_markdown_inline(explanation.overview)}</p>
</div>

<div class="card diagram">
  <h2>Architecture map</h2>
  {svg}
  <details style="margin-top:14px">
    <summary>Mermaid source</summary>
    <pre>{html.escape(mermaid)}</pre>
  </details>
</div>

<div class="card">
  <h2>Components</h2>
  {_table(["Component", "Path", "Files", "Lines", "Imported by", "Depends on", "Signals"], component_rows, numeric={2, 3, 4, 5})}
</div>

<div class="card">
  <h2>Connections</h2>
  {_table(["From", "Relation", "To", "Evidence"], edge_rows)}
</div>

{''.join(sections_html)}

<div class="card">
  <h2>Coverage</h2>
  <ul>{''.join(f'<li>{item}</li>' for item in coverage_items)}</ul>
</div>

{validation}

<footer>Generated by staticdiagram \u2014 deterministic static analysis, zero model calls.</footer>
</main>
</body>
</html>
"""
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(document, encoding="utf-8")
    return destination


def write_json(graph: DiagramGraph, destination: Path, extra: Optional[dict[str, Any]] = None) -> Path:
    payload: dict[str, Any] = graph.to_dict()
    if extra:
        payload.update(extra)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return destination


def write_facts(analysis: Analysis, explanation: Explanation, destination: Path) -> Path:
    payload = {
        "repository": {
            "owner": analysis.repo.owner,
            "name": analysis.repo.name,
            "branch": analysis.repo.branch,
            "commit": analysis.repo.commit,
            "origin": analysis.repo.origin,
        },
        "project": {
            "name": analysis.meta.name,
            "version": analysis.meta.version,
            "description": analysis.meta.description,
            "license": analysis.meta.license,
            "dependencies": analysis.meta.dependencies,
            "console_scripts": analysis.meta.console_scripts,
            "package_roots": analysis.meta.package_roots,
        },
        "explanation": explanation.facts,
        "components": [
            {
                "path": component.path,
                "label": component.label,
                "kind": component.kind,
                "files": component.files,
                "loc": component.loc,
                "inbound": component.inbound,
                "outbound": component.outbound,
                "pagerank": round(component.pagerank, 6),
                "score": round(component.score, 4),
                "signals": sorted(component.signals),
                "entrypoints": component.entrypoints,
                "routes": component.routes,
                "tasks": component.tasks,
                "primary_file": component.primary_file,
                "docstring": component.docstring,
            }
            for component in analysis.component_list()
        ],
        "component_edges": [
            {
                "from": edge.src,
                "to": edge.dst,
                "weight": edge.weight,
                "evidence_path": edge.evidence_path,
                "evidence_lineno": edge.evidence_lineno,
                "modules": dict(edge.modules.most_common(6)),
            }
            for edge in sorted(
                analysis.component_edges.values(), key=lambda item: -item.weight
            )[:200]
        ],
        "coverage": analysis.coverage.as_dict(),
        "infra": analysis.infra,
    }
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return destination


def validate(graph: DiagramGraph, analysis: Analysis) -> list:
    return validate_graph(graph, analysis.repo.file_tree)
