@dataclass
class Outputs:
    directory: Path
    mermaid: Optional[Path] = None
    svg: Optional[Path] = None
    html: Optional[Path] = None
    markdown: Optional[Path] = None
    graph_json: Optional[Path] = None
    facts_json: Optional[Path] = None
    repo_json: Optional[Path] = None
    files: list[Path] = field(default_factory=list)


def _links(analysis: Analysis, path: Optional[str]) -> str:
    if not path:
        return "\u2014"
    url = analysis.repo.github_url(path)
    return f"[`{path}`]({url})" if url else f"`{path}`"


def write_markdown(
    analysis: Analysis,
    explanation: Explanation,
    mermaid: str,
    destination: Path,
    svg_name: str = "diagram.svg",
) -> Path:
    repo = analysis.repo
    meta = analysis.meta
    lines: list[str] = []
    title = meta.name or repo.name
    lines.append(f"# {title} \u2014 architecture map")
    lines.append("")
    meta_bits = []
    if repo.owner:
        meta_bits.append(f"[{repo.slug}](https://github.com/{repo.slug})")
    else:
        meta_bits.append(repo.origin)
    meta_bits.append(f"branch `{repo.branch}`")
    if repo.commit:
        meta_bits.append(f"commit `{repo.commit[:10]}`")
    meta_bits.append("generated by static analysis \u2014 no AI")
    lines.append(" \u00b7 ".join(meta_bits))
    lines.append("")
    if meta.description:
        lines.append(f"> {meta.description}")
        lines.append("")
    lines.append(f"![Architecture map of {title}](./{svg_name})")
    lines.append("")

    for heading, body in explanation.sections:
        lines.append(f"## {heading}")
        lines.append("")
        lines.append(body)
        lines.append("")

    lines.append("## Mermaid source")
    lines.append("")
    lines.append("```mermaid")
    lines.append(mermaid)
    lines.append("```")
    lines.append("")

    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(lines), encoding="utf-8")
    return destination


