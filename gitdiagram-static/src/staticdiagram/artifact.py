"""Emit a GitDiagram-compatible storage artifact.

GitDiagram persists successful generations in R2 as a `DiagramArtifact`
(`src/server/storage/types.ts`) under the key
`public/v1/{username}/{repo}.json`. A graph produced here satisfies the same
contract, so a diagram built without any model can be dropped straight into that
bucket and the existing site will serve it — no provider call, no quota, no key.

    wrangler r2 object put BUCKET/public/v1/fastapi/fastapi.json \
        --file out/fastapi__fastapi/artifact.json --content-type application/json

Fields mirror `toStoredSessionSummary` and `GenerationSessionAudit`; costs are
zero because nothing was billed.
"""

from __future__ import annotations

import json
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Optional

from .depgraph import Analysis
from .explain import Explanation
from .model import DiagramGraph

PROVIDER = "static"
MODEL = "static-analyzer"
PRICING_MODEL = "static-analysis"


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")


def _zero_cost(kind: str = "actual") -> dict[str, Any]:
    return {
        "kind": kind,
        "approximate": False,
        "amountUsd": 0,
        "display": "$0.00",
        "pricingModel": PRICING_MODEL,
        "usage": {
            "inputTokens": 0,
            "outputTokens": 0,
            "totalTokens": 0,
            "reasoningTokens": 0,
            "cachedInputTokens": 0,
            "cacheWriteTokens": 0,
            "serviceTier": "default",
        },
        "note": "Generated by static analysis; no model was called.",
    }


def build_session_summary(
    analysis: Analysis,
    explanation: Explanation,
    graph: DiagramGraph,
    mermaid: str,
    session_id: Optional[str] = None,
) -> dict[str, Any]:
    repo = analysis.repo
    coverage = analysis.coverage
    timestamp = _now()
    return {
        "sessionId": session_id or str(uuid.uuid4()),
        "status": "succeeded",
        "stage": "complete",
        "provider": PROVIDER,
        "model": MODEL,
        "analysisModel": MODEL,
        "sourcePaths": sorted(analysis.facts)[:200],
        "unavailableSourceCount": coverage.files_failed,
        "quotaStatus": "finalized",
        "quotaBucket": "static",
        "quotaDateUtc": timestamp[:10],
        "actualCommittedTokens": 0,
        "quotaResetAt": None,
        "estimatedCost": _zero_cost("estimate"),
        "finalCost": _zero_cost("actual"),
        "graph": None,  # successful artifacts keep the graph at the top level
        "graphAttempts": [
            {
                "attempt": 1,
                "rawOutput": json.dumps(graph.to_dict(), ensure_ascii=False),
                "graph": None,
                "status": "succeeded",
                "createdAt": timestamp,
                "strippedPathCount": 0,
                "strippedEvidenceCount": 0,
                "filledEvidenceCount": sum(
                    1 for edge in graph.edges if edge.evidencePath
                ),
            }
        ],
        "stageUsages": [],
        "validationError": None,
        "failureStage": None,
        "compilerError": None,
        "renderError": None,
        "timeline": [
            {"stage": "repository", "message": f"Read {repo.slug}", "createdAt": timestamp},
            {
                "stage": "analysis",
                "message": (
                    f"Parsed {coverage.files_parsed} modules, resolved "
                    f"{coverage.imports_resolved} internal imports"
                ),
                "createdAt": timestamp,
            },
            {
                "stage": "graph",
                "message": f"Built {len(graph.nodes)} nodes and {len(graph.edges)} edges",
                "createdAt": timestamp,
            },
            {"stage": "complete", "message": "Diagram compiled", "createdAt": timestamp},
        ],
        "createdAt": timestamp,
        "updatedAt": timestamp,
        "compiledDiagram": mermaid,
        "explanation": explanation.overview,
    }


def build_artifact(
    analysis: Analysis,
    explanation: Explanation,
    graph: DiagramGraph,
    mermaid: str,
    visibility: str = "public",
    stargazer_count: Optional[int] = None,
    session_id: Optional[str] = None,
) -> dict[str, Any]:
    repo = analysis.repo
    timestamp = _now()
    return {
        "version": 1,
        "visibility": visibility,
        "username": repo.owner or repo.name,
        "repo": repo.name,
        "stargazerCount": stargazer_count,
        "diagram": mermaid,
        "explanation": explanation.overview,
        "graph": graph.to_dict(),
        "generatedAt": timestamp,
        "usedOwnKey": False,
        "latestSessionSummary": build_session_summary(
            analysis, explanation, graph, mermaid, session_id
        ),
        "lastSuccessfulAt": timestamp,
    }


def write_artifact(payload: dict[str, Any], destination: Path) -> Path:
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return destination


def artifact_key(owner: str, repo: str, visibility: str = "public") -> str:
    from urllib.parse import quote

    segment = lambda value: quote(value.strip().lower(), safe="")  # noqa: E731
    return f"{visibility}/v1/{segment(owner)}/{segment(repo)}.json"
